import type { Capability } from './dto/adapter.js';
import type { OAuthProviderTarget } from './oauth-provider.js';

export type MediaProviderGroup = 'image' | 'video';
export type MediaProviderKind = 'official' | 'hub';
export type MediaProviderAccess = 'public' | 'managed' | 'excluded';

/**
 * Cross-layer source of truth for built-in media providers.
 *
 * `providerId` is the stable ID persisted by Settings and Keychain.
 * `adapterId` is the runtime transport implementation. Several model cards may
 * intentionally share one hub transport (for example Wan through Replicate).
 */
export interface BuiltinMediaProviderCatalogEntry {
  group: MediaProviderGroup;
  providerId: string;
  adapterId: string;
  credentialId: string;
  name: string;
  kind: MediaProviderKind;
  access: MediaProviderAccess;
  oauthTarget?: OAuthProviderTarget;
  baseUrl: string;
  model: string;
  modelExample?: string;
  docsUrl: string;
  keyUrl: string;
  allowedHosts: readonly string[];
  capabilities: readonly Capability[];
  supportsReferenceImage?: boolean;
  supportsAudio?: boolean;
  qualityTiers?: readonly string[];
  defaultResolution?: string;
  defaultDurationSeconds?: number;
  outputFormats: readonly string[];
  notes?: string;
  excludedReason?: string;
}

