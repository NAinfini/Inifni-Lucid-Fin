function cloneEntry(entry: BuiltinMediaProviderCatalogEntry): BuiltinMediaProviderCatalogEntry {
  return {
    ...entry,
    allowedHosts: [...entry.allowedHosts],
    oauthTarget: entry.oauthTarget ? { ...entry.oauthTarget } : undefined,
    capabilities: [...entry.capabilities],
    qualityTiers: entry.qualityTiers ? [...entry.qualityTiers] : undefined,
    outputFormats: [...entry.outputFormats],
  };
}

export function listBuiltinMediaProviders(
  group?: MediaProviderGroup,
  options: { includeExcluded?: boolean } = {},
): BuiltinMediaProviderCatalogEntry[] {
  return MEDIA_PROVIDER_CATALOG.filter((entry) => (group ? entry.group === group : true))
    .filter((entry) => options.includeExcluded || entry.access !== 'excluded')
    .map(cloneEntry);
}

export function getBuiltinMediaProvider(
  group: MediaProviderGroup,
  providerId: string,
  options: { includeExcluded?: boolean } = {},
): BuiltinMediaProviderCatalogEntry | undefined {
  const normalizedId = providerId.trim().toLowerCase();
  const entry = MEDIA_PROVIDER_CATALOG.find(
    (candidate) => candidate.group === group && candidate.providerId === normalizedId,
  );
  if (!entry || (!options.includeExcluded && entry.access === 'excluded')) return undefined;
  return cloneEntry(entry);
}

export function resolveBuiltinMediaAdapterId(
  providerId: string,
  group: MediaProviderGroup,
): string | undefined {
  return getBuiltinMediaProvider(group, providerId)?.adapterId;
}

export function resolveBuiltinMediaCredentialId(
  providerId: string,
  group: MediaProviderGroup,
): string | undefined {
  return getBuiltinMediaProvider(group, providerId)?.credentialId;
}

/** Resolve a provider ID when every media group maps it to the same transport. */
export function resolveUnambiguousBuiltinMediaAdapterId(providerId: string): string | undefined {
  const normalizedId = providerId.trim().toLowerCase();
  const adapterIds = new Set(
    MEDIA_PROVIDER_CATALOG.filter(
      (entry) => entry.access !== 'excluded' && entry.providerId === normalizedId,
    ).map((entry) => entry.adapterId),
  );
  return adapterIds.size === 1 ? [...adapterIds][0] : undefined;
}
